-- TickCart 秒杀商城 · 数据库迁移 V19
-- 内容：分类级「库存预警线」
--
-- 目的
--   后台商品列表要标出「库存告急」的商品，但"多少算少"不能一刀切：
--   食品生鲜周转快、有保质期，剩 20 件就该补；大家电单价高、周转极慢，
--   剩 3 件也不算紧张。同一个阈值套在所有商品上，要么漏报要么天天误报。
--
-- 为什么放分类而不是商品
--   · 商品级（156 条）运营配不完，最后一定是「字段开了但全空」；
--   · 分类级只有 20 条，且「周转速度」本来就由品类决定，配置点少而语义对。
--
-- ★为什么是 NULL 而不是 DEFAULT 10
--   NULL = 没配过 = 继承上一级（父分类 → 全局配置 tickcart.stock.warn-threshold）。
--   10   = 配过 = 就用 10。
--   用 DEFAULT 10 会把「继承」和「恰好等于 10」混成一种状态 —— 以后把全局默认值
--   从 10 调到 20 时，存量分类不会跟着变，且没人能解释为什么。
--
-- 取值优先级（见 StockWarnService）
--   自身 stock_warn_threshold → 沿 parent_id 上溯最近的祖先值 → 全局配置
-- =============================================================================

ALTER TABLE `product_category`
    ADD COLUMN `stock_warn_threshold` INT NULL DEFAULT NULL
        COMMENT '库存预警线：库存低于该值标记告急；NULL 表示继承父分类/全局配置'
        AFTER `status`;

-- -----------------------------------------------------------------------------
-- 种子：只给「周转特征明显」的几个分类配值，其余保持 NULL 走全局默认
--   刻意不铺满 —— 全配等于把「继承」这条链路藏起来，演示时看不出分层效果
-- -----------------------------------------------------------------------------

-- 食品生鲜（23）：周转快、有保质期，宁可多备
UPDATE `product_category` SET `stock_warn_threshold` = 30 WHERE `id` = 23;
-- 鞋类（5）：尺码分散，总量 20 也可能某个码已经 0
UPDATE `product_category` SET `stock_warn_threshold` = 8  WHERE `id` = 5;
-- 家电（16）：单价高、周转极慢，几乎不备货
UPDATE `product_category` SET `stock_warn_threshold` = 3  WHERE `id` = 16;

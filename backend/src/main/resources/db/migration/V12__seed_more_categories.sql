-- TickCart 秒杀商城 · 数据库迁移 V12
-- 内容：把「有分类但没商品」的 17 个分类补上商品，每个分类 6 个，共 102 个。
--
-- 背景
--   分类 7~23（护肤彩妆…食品生鲜）是开发者在后台手工建的，**仓库里原先没有任何迁移记录**，
--   而且它们下面一个商品都没有：首页点进去是「暂无商品」，搜相关词也是空结果。
--   V9 的注释里写过「其余 17 个分类有意不固化……将来若要，另起迁移补」——本迁移就是那个迁移。
--   所以这里**先补分类、再补商品**：否则从零建库时分类不存在，商品的外键也无处可挂。
--
-- 幂等性
--   · 分类：INSERT IGNORE，已存在则整行跳过（开发库里这 17 个分类已经存在，名字一致）。
--   · 商品：INSERT IGNORE，按主键去重。
--   · SKU：product_sku 没有能唯一标识「同商品同规格」的键，改用 NOT EXISTS 守卫，
--     该商品只要已有任何 SKU 就整批跳过。
--
-- 商品 id 用 201~302
--   已确认 201~320 在开发库与种子库里都空闲（现有商品占用 1,2,6,7,101~156，
--   另 3,4,5 是 V8 逻辑删除的演示商品）。显式给 id 是为了让 SKU 与图集能直接引用。
--
-- 图片
--   主图取自 Unsplash 免费图（授权见 imgs/SOURCES.md），已缩到 900px / q80，
--   与既有 56 张商品图同规格（平均 ~78KB）。
--   SKU 不设独立图（sku_image 为 NULL），详情页会自动回退到商品主图。
-- =============================================================================


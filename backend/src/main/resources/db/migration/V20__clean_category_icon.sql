-- TickCart 秒杀商城 · 数据库迁移 V20
-- 内容：清理分类表里的无效图标值
--
-- 背景
--   `product_category.icon` 这个字段商城端**根本不渲染** —— 首页分类栏只取
--   `cat.name`（见 HomeView.vue 的 categoryTabs）。后台表单却一直有个「图标URL」
--   输入框，要求人手填路径，于是唯一填过的那条是这样的：
--
--     id=5（鞋类） icon = 'D:\develop\coding\TickCart\imgs\iphone_17__...jpg'
--
--   本地磁盘绝对路径 + 反斜杠，就算哪天前台渲染了也是裂图；而且这张图是 iPhone，
--   挂在「鞋类」下面，明显是当年测试随手填的。
--
-- 本次改动
--   1. 后台表单去掉「图标URL」输入框（列保留，将来真要做图标宫格时不用再迁移）；
--   2. 这里把「不像 URL」的存量值清空，避免以后有人看数据库以为这个字段在用。
--
-- 保留规则
--   只清掉不以 '/' 开头的值（合法值应该是 /img/xxx.png 这种站内相对路径）。
--   如果将来有人填了 http(s):// 开头的外链，也会被清 —— 当前库里没有这种数据。
-- =============================================================================

UPDATE `product_category`
SET `icon` = NULL
WHERE `icon` IS NOT NULL
  AND `icon` <> ''
  AND `icon` NOT LIKE '/%';

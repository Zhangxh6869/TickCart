-- =============================================================================
-- TickCart 秒杀商城 · 数据库迁移 V8
-- 内容：把 V4 种子里的演示商品 3 / 4 / 5（智能变频空调、简约纯棉T恤、进口车厘子）
--       连同其 SKU 一并置为逻辑删除，与开发者后台删除后的状态保持一致。
--
-- 背景
--   这 3 个商品的主图指向 /img/demo/{ac,tshirt,cherry}.png，而仓库中并不存在
--   imgs/demo/ 目录（演示图片改由 /img/{phones,shoes,clothing}/** 提供）。
--   V7 只修好了仍在售的 1 / 2 / 6 / 7，并物理删除了图集里的 /img/demo/% 行，
--   但这 3 个商品的 main_image 仍是死链 —— 于是全新克隆的环境里会多出 3 个碎图商品。
--   开发者在后台已把这 3 个商品删除，本迁移把这一步固化为种子数据。
--
-- 说明
--   · 只改数据，不动表结构。
--   · 幂等：带 deleted = 0 条件，重复执行不会产生额外影响。
--   · 与后台删除行为一致：只置 deleted，不动 status。
--   · product_image 无 deleted 列（该表是物理删除），且 V7 已清掉 /img/demo/% 行，
--     故此处无需为 3/4/5 处理图集。
-- =============================================================================

UPDATE `product` SET `deleted` = 1 WHERE `id` IN (3, 4, 5) AND `deleted` = 0;

UPDATE `product_sku` SET `deleted` = 1 WHERE `product_id` IN (3, 4, 5) AND `deleted` = 0;

-- -----------------------------------------------------------------------------
-- 附带修复：清掉 V7 在全新库中留下的孤儿图集行
--
-- 商品 6（iPhone Air）与 7（iPhone Duo）是开发者在后台手工新增的，并不在种子数据里；
-- V7 却按「1/2/6/7 都在」的假设给 6/7 插入了图集。线上库因为这两个商品确实存在
-- 所以看不出问题，但全新克隆后 product 表里没有 6/7，于是留下 6 行孤儿图集。
-- 这些行不会被任何查询读到（详情页要求商品本身存在），但属于脏数据，这里一并清掉。
-- =============================================================================

DELETE `i` FROM `product_image` `i`
LEFT JOIN `product` `p` ON `p`.`id` = `i`.`product_id`
WHERE `p`.`id` IS NULL;
